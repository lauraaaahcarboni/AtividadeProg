package fundamentosScanner;

public class list2Atv7 {

	public static void main(String[] args) {

		double nota = 8.95;
		int notaI;
		double notaD;

		notaI = (int) nota;
		notaD = notaI;

		System.out.println("Nota original (double): " + nota);
		System.out.println("Nota convertida para int: " + notaI);
		System.out.println("Nota convertida de volta para double: " + notaD);

	}

}